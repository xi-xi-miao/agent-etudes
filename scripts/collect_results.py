# per-attempt collection
# --------------------------------------------------------------------------


def solutions_glob_for(repo: Path, cid: str) -> str:
    """``solutions_glob`` from the challenge manifest, or the default."""
    challenge_dir = repo / "challenges" / cid
    if not (challenge_dir / "challenge.yaml").is_file():
        return DEFAULT_SOLUTIONS_GLOB
    try:
        manifest = load_manifest(challenge_dir)
    except ManifestError as exc:
        warn(f"{exc}; falling back to {DEFAULT_SOLUTIONS_GLOB!r}")
        return DEFAULT_SOLUTIONS_GLOB
    value = manifest.get("solutions_glob") or DEFAULT_SOLUTIONS_GLOB
    return str(value)


def find_base(repo: Path, item: Attempt, remote: str) -> tuple[str | None, str | None]:
    """``(base_sha, start_tag)`` for one attempt.

    Prefers ``merge-base(<ref>, <cid>-start)``. When the start tag does not
    exist yet the base falls back to ``main`` with a warning, and when even
    that is unavailable the timeline simply covers the whole branch history.
    """
    tag = f"{item.cid}-start"
    if git_ok(["rev-parse", "--verify", "--quiet", f"refs/tags/{tag}^{{commit}}"], cwd=repo):
        try:
            base = git(["merge-base", f"refs/tags/{tag}", item.ref], cwd=repo).strip()
        except subprocess.CalledProcessError:
            warn(
                f"{item.branch}: no common history with the tag {tag}; "
                "the timeline will cover the whole branch"
            )
            return None, tag
        return base, tag

    warn(
        f"{item.branch}: the start tag {tag} does not exist here "
        f"(git fetch --tags {remote}?); using main as the base instead"
    )
    for candidate in ("refs/heads/main", f"refs/remotes/{remote}/main"):
        if git_ok(["rev-parse", "--verify", "--quiet", f"{candidate}^{{commit}}"], cwd=repo):
            try:
                base = git(["merge-base", candidate, item.ref], cwd=repo).strip()
            except subprocess.CalledProcessError:
                break
            return base, None
    warn(
        f"{item.branch}: neither {item.cid}-start nor main could be resolved; "
        "the timeline will cover the whole branch history"
    )
    return None, None


def list_tree(repo: Path, ref: str) -> list[str]:
    """Every path stored on ``ref`` (NUL-separated, so odd names survive)."""
    out = git(["ls-tree", "-r", "-z", "--name-only", ref], cwd=repo)
    return [p for p in out.split("\0") if p]


def choose_paths(all_paths: list[str], solutions_glob: str) -> list[str]:
    """The branch paths worth copying: session/, solutions, reviews/, SVGs.

    ``solver/`` is never copied, even when a challenge manifest's
    ``solutions_glob`` is loose enough to match a file in it: solver code stays
    on the attempt branch, where it can be read with its own history.
    """
    present = set(all_paths)
    matcher = _glob_to_re(solutions_glob)
    keep: set[str] = set()
    for path in all_paths:
        if path.startswith(NEVER_COPY_PREFIXES):
            continue
        if path.startswith(SESSION_PREFIX) or path.startswith(EXTRA_PREFIXES):
            keep.add(path)
        elif matcher.match(path):
            keep.add(path)
            sibling = path.rsplit(".", 1)[0] + ".svg" if "." in path else path + ".svg"
            if sibling in present:
                keep.add(sibling)
    return sorted(keep)


def export_paths(repo: Path, ref: str, paths: list[str], dest: Path) -> None:
    """``git archive <ref> <paths> | tar -x`` into ``dest``. No checkout."""
    dest.mkdir(parents=True, exist_ok=True)
    if not paths:
        return
    archive = subprocess.Popen(
        ["git", "archive", "--format=tar", ref, *paths],
        cwd=str(repo),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    assert archive.stdout is not None
    untar = subprocess.Popen(
        ["tar", "-x", "-f", "-", "-C", str(dest)],
        stdin=archive.stdout,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    archive.stdout.close()
    _, untar_err = untar.communicate()
    # read git's stderr before waiting: a long complaint would otherwise fill
    # the pipe buffer and deadlock the process we are waiting for
    archive_err = archive.stderr.read() if archive.stderr else b""
    if archive.stderr:
        archive.stderr.close()
    archive.wait()
    if archive.returncode != 0:
        raise EtudesError(
            f"git archive {ref} failed: "
            f"{archive_err.decode('utf-8', 'replace').strip() or 'unknown error'}"
        )
    if untar.returncode != 0:
        raise EtudesError(
            "unpacking the archive failed: "
            f"{untar_err.decode('utf-8', 'replace').strip() or 'unknown error'}"
        )


def build_timeline(repo: Path, base: str | None, ref: str) -> str:
    """``<sha> +H:MM <subject>`` per commit, elapsed from the first commit."""
    revs = f"{base}..{ref}" if base else ref
    try:
        out = git(["log", "--reverse", "--format=%h %at %s", revs], cwd=repo)
    except subprocess.CalledProcessError as exc:
        raise EtudesError(
            f"could not read the commit history of {ref}: "
            f"{(exc.stderr or '').strip()}"
        ) from None
    lines: list[str] = []
    first_epoch: int | None = None
    for raw in out.splitlines():
        if not raw.strip():
            continue
        parts = raw.split(" ", 2)
        sha = parts[0]
        try:
            epoch = int(parts[1])
        except (IndexError, ValueError):
            continue
        subject = parts[2] if len(parts) > 2 else ""
        if first_epoch is None:
            first_epoch = epoch
        minutes = max(0, (epoch - first_epoch) // 60)
        lines.append(f"{sha} {fmt_elapsed(minutes)} {subject}".rstrip())
    return "".join(line + "\n" for line in lines)


def taxonomy_version_of(staging: Path) -> str | None:
    """``taxonomy_version`` from the copied ``annotations.md`` frontmatter."""
    annotations = staging / "annotations.md"
    if not annotations.is_file():
        return None
    try:
        meta, _ = split_frontmatter(
            annotations.read_text(encoding="utf-8", errors="replace"), annotations
        )
    except EtudesError:
        return None
    value = meta.get("taxonomy_version")
    return None if value is None else str(value)


def place_files(scratch: Path, staging: Path, paths: list[str]) -> list[str]:
    """Move the exported files into their final shape inside ``staging``.

    ``session/`` is flattened onto the target root; every other path keeps its
    position (``solutions/...``, ``reviews/...``). Returns the branch paths
    that really were copied, which is what the run's summary line counts.
    """
    copied: list[str] = []
    for path in paths:
        source = scratch / path
        if not source.is_file():
            continue
        if path.startswith(SESSION_PREFIX):
            relative = path[len(SESSION_PREFIX) :]
        else:
            relative = path
        if not relative:
            continue
        target = staging / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        copied.append(path)
    return copied


def preserve_reviews(target: Path, staging: Path) -> list[str]:
    """Carry cross-annotations already in ``results/`` over into ``staging``.

    A reviewer commits ``results/<cid>/<p>/<n>/reviews/<reviewer>.annotations.md``
    straight to ``main`` (CONTRIBUTING, "cross-annotation") instead of pushing
    to somebody else's attempt branch, so rebuilding the directory from the
    branch must not throw those files away. A review that also exists on the
    branch is taken from the branch. Returns the relative paths kept.
    """
    source = target / REVIEWS_DIR
    kept: list[str] = []
    if not source.is_dir():
        return kept
    for path in sorted(source.rglob("*")):
        if path.is_symlink() or not path.is_file():
            continue
        relative = path.relative_to(target)
        destination = staging / relative
        if destination.exists():
            continue  # the branch carries its own copy; that one wins
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, destination)
        kept.append(relative.as_posix())
    return kept


def collect_one(repo: Path, results_root: Path, item: Attempt, remote: str) -> str:
    """Collect one attempt and return the one-line report for it."""
    head_sha = git(["rev-parse", f"{item.ref}^{{commit}}"], cwd=repo).strip()
    base_sha, start_tag = find_base(repo, item, remote)
    glob_pattern = solutions_glob_for(repo, item.cid)

    all_paths = list_tree(repo, item.ref)
    paths = choose_paths(all_paths, glob_pattern)
    if not paths:
        warn(
            f"{item.branch}: nothing to copy -- no session/ directory and no "
            f"file matching {glob_pattern!r} on the branch"
        )

    target = results_root / item.cid / item.participant / str(item.attempt)

    with tempfile.TemporaryDirectory(prefix="etudes-collect-") as tmp:
        tmp_path = Path(tmp)
        scratch = tmp_path / "export"
        staging = tmp_path / "staging"
        staging.mkdir(parents=True)
        export_paths(repo, item.ref, paths, scratch)
        copied = place_files(scratch, staging, paths)
        # before the manifest: the byte comparison in _collected_at has to see
        # the final tree, or a preserved review would churn the timestamp.
        kept_reviews = preserve_reviews(target, staging)

        (staging / TIMELINE_NAME).write_text(
            build_timeline(repo, base_sha, item.ref), encoding="utf-8"
        )

        manifest = {
            "branch": item.branch,
            "head_sha": head_sha,
            "base_sha": base_sha,
            "start_tag": start_tag,
            "cid": item.cid,
            "participant": item.participant,
            "attempt": item.attempt,
            "collected_at": None,
            "taxonomy_version": taxonomy_version_of(staging),
            "copied_paths": paths,
        }
        manifest["collected_at"] = _collected_at(target, staging, manifest)
        (staging / MANIFEST_NAME).write_text(
            MANIFEST_HEADER + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True),
            encoding="utf-8",
        )

        if target.exists():
            shutil.rmtree(target)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(staging), str(target))

    files = [p for p in target.rglob("*") if p.is_file()]
    total = sum(p.stat().st_size for p in files)
    try:
        shown = target.relative_to(Path.cwd())
    except ValueError:
        shown = target
    # Two counts, never one: a review carried over from results/ is not
    # something the branch supplied, and the old single total made a
    # maintainer's own file look like the participant's work.
    return (
        f"{item.label}  <- {item.branch}  "
        f"{len(copied)} file(s) copied from the branch, "
        f"{len(kept_reviews)} review file(s) kept, "
        f"{_human_bytes(total)}  ({shown})"
    )


def _collected_at(target: Path, staging: Path, manifest: dict) -> str:
    """Now, in ISO UTC -- or the previous value when nothing has changed.

    Keeping the timestamp makes a re-run byte-identical, so the collector can
    be run again at any time without producing a pointless diff.
    """
    now = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    now = now.replace("+00:00", "Z")
    old_manifest_path = target / MANIFEST_NAME
    if not old_manifest_path.is_file():
        return now
    try:
        old = yaml.safe_load(old_manifest_path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError):
        return now
    if not isinstance(old, dict):
        return now
    previous = old.get("collected_at")
    if not isinstance(previous, str):
        return now
    comparable_old = {k: v for k, v in old.items() if k != "collected_at"}
    comparable_new = {k: v for k, v in manifest.items() if k != "collected_at"}
    if comparable_old != comparable_new:
        return now
    old_files = {
        k: v for k, v in _tree_files(target).items() if k != MANIFEST_NAME
    }
    new_files = _tree_files(staging)
    if old_files != new_files:
        return now
    return previous


