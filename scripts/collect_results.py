#!/usr/bin/env python3
"""Collect attempt branches into the ``results/`` tree.

Every participant works on a branch ``attempt/<cid>/<participant>/<n>``. This
script copies the *session artifacts* (and the solution data, never the solver
code) off those branches into ``results/<cid>/<participant>/<n>/`` so the
annotations can be linted, summarised and compared in one place, and so the
whole round can be reviewed as a normal pull request.

Usage
-----
    collect_results.py [<ref>...] [--repo DIR] [--results DIR] [--remote NAME]

With no explicit refs it enumerates every local ``attempt/...`` branch and
every ``<remote>/attempt/...`` branch, preferring the local one when both
exist. Refs that do not look like ``attempt/<cid>/<participant>/<n>`` are
reported as a warning and skipped.

What lands in ``results/<cid>/<participant>/<n>/``
-------------------------------------------------
* the contents of ``session/`` from the branch, flattened to the target root
  (``session/annotations.md`` -> ``annotations.md``,
  ``session/decisions/dr-001.md`` -> ``decisions/dr-001.md``),
* ``solutions/`` -- the files matching the challenge manifest's
  ``solutions_glob`` plus any sibling ``.svg`` rendering,
* ``reviews/`` -- cross-annotations, from the branch if it carries any and
  otherwise the ones already committed into ``results/``,
* a generated ``manifest.yaml`` (provenance only -- no measures),
* a generated ``git-timeline.txt``: one line per commit, ``<sha> +H:MM
  <subject>``, elapsed from the first commit of the attempt.

The working tree is never checked out and never switched: content is read with
``git ls-tree``/``git archive`` and unpacked into a scratch directory first.

Re-running is idempotent: the target directory is rebuilt from scratch (so
files deleted on the branch disappear here too) and, when nothing at all has
changed, even ``collected_at`` keeps its previous value so the run produces no
diff. The one exception is ``reviews/``: cross-annotations are committed into
``results/`` by a reviewer rather than pushed to somebody else's attempt
branch, so files already there are carried over instead of being rebuilt away.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import yaml  # noqa: E402

from etudes_lib import (  # noqa: E402
    BRANCH_RE,
    EtudesError,
    ManifestError,
    fmt_elapsed,
    git,
    git_ok,
    load_manifest,
    repo_root_from,
    split_frontmatter,
)

DEFAULT_SOLUTIONS_GLOB = "solutions/**/*.json"
SESSION_PREFIX = "session/"
EXTRA_PREFIXES = ("reviews/",)
REVIEWS_DIR = "reviews"
#: Solver code stays on the attempt branch, whatever a challenge manifest's
#: ``solutions_glob`` happens to match.
NEVER_COPY_PREFIXES = ("solver/",)
MANIFEST_NAME = "manifest.yaml"
TIMELINE_NAME = "git-timeline.txt"
MANIFEST_HEADER = (
    "# Generated by scripts/collect_results.py -- provenance only.\n"
    "# Do not edit by hand; re-run the collector instead.\n"
)


# --------------------------------------------------------------------------
# small helpers
# --------------------------------------------------------------------------


def warn(text: str) -> None:
    """One warning line on stderr. Warnings never fail the run."""
    print(f"warning: {text}", file=sys.stderr)


def _glob_to_re(pattern: str) -> "re.Pattern[str]":
    """Translate a ``solutions_glob`` into a regex for slash-separated paths.

    Not provided by ``etudes_lib``; ``fnmatch`` cannot express ``**`` and
    ``pathlib.PurePath.match`` treats ``**`` as a single ``*`` on Python 3.11.
    Supported: ``**/`` (zero or more directories), ``*`` (anything but ``/``),
    ``?`` (one character but ``/``), ``[...]`` character classes.
    """
    out = ["^"]
    i = 0
    n = len(pattern)
    while i < n:
        ch = pattern[i]
        if pattern.startswith("**/", i):
            out.append("(?:[^/]+/)*")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif ch == "*":
            out.append("[^/]*")
            i += 1
        elif ch == "?":
            out.append("[^/]")
            i += 1
        elif ch == "[":
            close = pattern.find("]", i + 1)
            if close == -1:
                out.append(re.escape(ch))
                i += 1
            else:
                body = pattern[i + 1 : close]
                if body.startswith("!"):
                    body = "^" + body[1:]
                out.append("[" + body.replace("\\", "\\\\") + "]")
                i = close + 1
        else:
            out.append(re.escape(ch))
            i += 1
    out.append("$")
    return re.compile("".join(out))


def _human_bytes(n: int) -> str:
    if n < 1024:
        return f"{n} B"
    if n < 1024 * 1024:
        return f"{n / 1024:.1f} KiB"
    return f"{n / (1024 * 1024):.1f} MiB"


def _tree_files(root: Path) -> dict[str, bytes]:
    """Every regular file under ``root`` as ``{relative posix path: bytes}``."""
    out: dict[str, bytes] = {}
    for path in sorted(root.rglob("*")):
        if path.is_file() and not path.is_symlink():
            out[path.relative_to(root).as_posix()] = path.read_bytes()
    return out


