def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="collect_results.py",
        description=(
            "Copy session artifacts and solutions off attempt/<cid>/"
            "<participant>/<n> branches into results/. Never checks out and "
            "never copies solver code."
        ),
        epilog=(
            "With no refs, every local attempt branch and every "
            "remote-tracking attempt branch is collected (local wins)."
        ),
    )
    parser.add_argument(
        "refs",
        nargs="*",
        metavar="REF",
        help="attempt branches to collect (default: all attempt/ branches)",
    )
    parser.add_argument(
        "--repo",
        metavar="DIR",
        help="repository to read from (default: the repository containing the "
        "current directory)",
    )
    parser.add_argument(
        "--results",
        metavar="DIR",
        help="where to write the collected attempts (default: <repo>/results)",
    )
    parser.add_argument(
        "--remote",
        default="origin",
        metavar="NAME",
        help="remote whose attempt branches are also considered "
        "(default: origin)",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    try:
        repo = (
            Path(args.repo).resolve()
            if args.repo
            else repo_root_from(Path.cwd())
        )
    except EtudesError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if not repo.is_dir():
        print(f"error: {args.repo}: no such directory", file=sys.stderr)
        return 1
    if not git_ok(["rev-parse", "--git-dir"], cwd=repo):
        print(
            f"error: {repo} is not a git repository; point --repo at a clone "
            "of agent-etudes",
            file=sys.stderr,
        )
        return 1

    results_root = Path(args.results).resolve() if args.results else repo / "results"

    try:
        if args.refs:
            attempts = resolve_explicit(repo, args.refs, args.remote)
        else:
            attempts = select_attempts(discover_refs(repo, args.remote), args.remote)
    except EtudesError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as exc:
        print(
            f"error: git failed while listing branches: "
            f"{(exc.stderr or '').strip()}",
            file=sys.stderr,
        )
        return 1

    if not attempts:
        print(
            "No attempt branches to collect. Attempt branches are named "
            "attempt/<cid>/<participant>/<n>, for example attempt/c001/alice/1."
        )
        return 0

    results_root.mkdir(parents=True, exist_ok=True)
    failures = 0
    for item in attempts:
        try:
            print(collect_one(repo, results_root, item, args.remote))
        except EtudesError as exc:
            failures += 1
            print(f"error: {item.branch}: {exc}", file=sys.stderr)
        except subprocess.CalledProcessError as exc:
            failures += 1
            print(
                f"error: {item.branch}: git failed: {(exc.stderr or '').strip()}",
                file=sys.stderr,
            )

    print(
        "\nReview every collected file for secrets (keys, tokens, customer "
        "data, private paths) before you open the pull request -- transcripts "
        "and harness configs are the risky ones."
    )
    return 1 if failures else 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
