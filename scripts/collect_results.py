# ref discovery
# --------------------------------------------------------------------------


class Attempt:
    """One attempt branch selected for collection."""

    def __init__(self, ref: str, branch: str, cid: str, participant: str, attempt: int):
        self.ref = ref  # the ref actually read (may be a remote-tracking ref)
        self.branch = branch  # attempt/<cid>/<participant>/<n>
        self.cid = cid
        self.participant = participant
        self.attempt = attempt

    @property
    def label(self) -> str:
        return f"{self.cid}/{self.participant}/{self.attempt}"


def _strip_ref_prefix(refname: str, remote: str) -> str:
    """``refs/remotes/origin/attempt/c001/a/1`` -> ``attempt/c001/a/1``."""
    if refname.startswith("refs/heads/"):
        return refname[len("refs/heads/") :]
    if refname.startswith("refs/remotes/"):
        # drop the remote name, whichever remote it is
        rest = refname[len("refs/remotes/") :]
        _, sep, tail = rest.partition("/")
        return tail if sep else rest
    if refname.startswith(f"{remote}/"):
        return refname[len(remote) + 1 :]
    return refname


def discover_refs(repo: Path, remote: str) -> list[str]:
    """All refs under the ``attempt/`` namespace, local and remote-tracking.

    The patterns below are deliberately a superset of ``attempt/*/*/*``: a
    branch such as ``attempt/typo`` should produce a warning rather than be
    silently ignored.
    """
    patterns = [
        "refs/heads/attempt/*/*/*",
        "refs/heads/attempt",
        f"refs/remotes/{remote}/attempt/*/*/*",
        f"refs/remotes/{remote}/attempt",
    ]
    out = git(["for-each-ref", "--format=%(refname)", *patterns], cwd=repo)
    return [line for line in out.splitlines() if line.strip()]


def select_attempts(refnames: list[str], remote: str) -> list[Attempt]:
    """Filter to well-formed attempt refs, preferring local over remote."""
    chosen: dict[str, Attempt] = {}
    for refname in refnames:
        branch = _strip_ref_prefix(refname, remote)
        m = BRANCH_RE.fullmatch(branch)
        if not m:
            warn(
                f"{refname}: not an attempt branch -- expected "
                "attempt/<cid>/<participant>/<n>, for example "
                "attempt/c001/alice/2; skipping"
            )
            continue
        item = Attempt(refname, branch, m.group(1), m.group(2), int(m.group(3)))
        previous = chosen.get(branch)
        if previous is None:
            chosen[branch] = item
        elif previous.ref.startswith("refs/heads/"):
            continue  # local already wins
        elif item.ref.startswith("refs/heads/"):
            chosen[branch] = item
    return [chosen[key] for key in sorted(chosen)]


def resolve_explicit(repo: Path, refs: list[str], remote: str) -> list[Attempt]:
    """Turn user-supplied refs into attempts, erroring on unknown refs."""
    refnames: list[str] = []
    for ref in refs:
        if not git_ok(["rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}"], cwd=repo):
            raise EtudesError(
                f"{ref}: no such branch, tag or commit in {repo}. Fetch it "
                f"first (git fetch {remote}) or check the spelling."
            )
        full = git(
            ["rev-parse", "--symbolic-full-name", ref], cwd=repo
        ).strip()
        refnames.append(full or ref)
    return select_attempts(refnames, remote)


